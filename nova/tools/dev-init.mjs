// Creates nova/.env with random, local-only database passwords for the
// Docker dev stack. Never overwrites an existing .env, and never prints the
// values. .env is gitignored; the variables are listed in .env.example.

import { existsSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const target = fileURLToPath(new URL('../.env', import.meta.url));

if (existsSync(target)) {
  console.log('.env already exists; left unchanged.');
  process.exit(0);
}

const secret = () => randomBytes(24).toString('base64url');

writeFileSync(
  target,
  [
    '# Local development only. Generated by tools/dev-init.mjs; never commit.',
    `NOVA_DB_PASSWORD=${secret()}`,
    `NOVA_DB_ROOT_PASSWORD=${secret()}`,
    'NOVA_HTTP_PORT=8080',
    'NOVA_MAIL_UI_PORT=8025',
    '',
  ].join('\n'),
  { flag: 'wx' },
);
console.log('Created .env with fresh local passwords.');
