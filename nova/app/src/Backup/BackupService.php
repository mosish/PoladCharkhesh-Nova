<?php

declare(strict_types=1);

namespace Nova\Backup;

use Nova\Audit\AuditLog;
use Nova\Core\Files;
use Nova\Core\Sql;
use Nova\Publish\Clock;
use PDO;
use Throwable;

/**
 * Layered backups (05 §18, D13/D23), one set at a time:
 *
 * - **Database:** the consistent-snapshot dump (`DatabaseDump`).
 * - **Media and documents:** an incremental, content-addressed copy plus a
 *   manifest (`MediaFiles`).
 * - **Releases:** a backup never touches `_site` or its releases; the
 *   manifest only records which retained releases existed, so a restore can
 *   say which rollback targets are still on disk. Static releases are
 *   regenerated by publishing and are not copied.
 * - **Never included:** configuration and secrets (`config.php`, `.env`),
 *   PHP sessions, the code, generated releases, vendor, and the hashed-address
 *   throttle tables.
 *
 * Every run is audited, success or failure. Triggers: `scheduler` (cron),
 * `fallback` (first Admin request of the day, only when no scheduler runs),
 * `manual`, and the safety copies `pre_migration` and `pre_restore`.
 *
 * @phpstan-import-type Manifest from BackupManifest
 */
final class BackupService
{
    public const array TRIGGERS = ['scheduler', 'fallback', 'manual', 'pre_migration', 'pre_restore'];
    /** The Migrator's named lock (`Nova\Migration\Migrator`). */
    private const string MIGRATION_LOCK = 'nova_migrate';

    /**
     * @param \Closure(): PDO $dumpConnection a connection of its own for the snapshot
     * @param \Closure(): list<array{id: string, status: string, manifest_sha256: ?string}> $releases the retained releases, for the manifest
     */
    public function __construct(
        private readonly PDO $pdo,
        private readonly \Closure $dumpConnection,
        private readonly BackupPaths $paths,
        private readonly BackupConfig $config,
        private readonly string $mediaDir,
        private readonly Clock $clock,
        private readonly string $appVersion,
        private readonly \Closure $releases,
    ) {}

    /**
     * @return array{id: string, at: int, trigger: string, schema_version: int, db_bytes: int, tables: int, media_files: int, media_copied: int, missing: list<string>}
     *
     * @throws BackupError locked, io
     */
    public function run(string $trigger = 'manual', string $origin = 'cli', bool $prune = true): array
    {
        if (!\in_array($trigger, self::TRIGGERS, true)) {
            throw new BackupError('invalid_target', "Unknown backup trigger {$trigger}.");
        }
        $this->paths->ensure();
        $lock = fopen($this->paths->lockFile(), 'c');
        if ($lock === false || !flock($lock, LOCK_EX | LOCK_NB)) {
            throw new BackupError('locked', 'Another backup or restore is running.');
        }
        // A migration changes table definitions the dump reads; a normal backup waits for it (the pre-migration copy runs inside it).
        $schemaLock = $trigger !== 'pre_migration';
        if ($schemaLock && Sql::int($this->pdo, 'SELECT GET_LOCK(?, 10)', [self::MIGRATION_LOCK]) !== 1) {
            flock($lock, LOCK_UN);
            fclose($lock);

            throw new BackupError('locked', 'A migration is running; the backup would see a half-changed schema. Try again when it has finished.');
        }
        $id = null;
        try {
            $this->sweepTemp();
            $at = $this->clock->now();
            $id = 'B-' . gmdate('Ymd-His', $at) . '-' . bin2hex(random_bytes(2));
            $dump = ($this->dumpConnection)();
            $gz = $this->paths->dump($id);
            $stats = DatabaseDump::write($dump, $gz);
            $expected = MediaFiles::expected($this->pdo);
            $media = MediaFiles::snapshot($expected, $this->mediaDir, $this->paths->store());
            $warnings = $media['missing'] === [] ? [] : [\count($media['missing']) . ' media or document files named by the database were not on disk and could not be backed up.'];

            $manifest = [
                'format' => BackupManifest::FORMAT, 'id' => $id, 'at' => $at, 'created_at' => gmdate('Y-m-d\TH:i:s\Z', $at), 'trigger' => $trigger,
                'app_version' => $this->appVersion, 'schema_version' => $stats['schema_version'],
                'db' => ['file' => 'db/' . $id . '.sql.gz', 'sha256' => (string) hash_file('sha256', $gz), 'bytes' => (int) filesize($gz), 'statements' => $stats['statements'], 'tables' => $stats['tables']],
                'media' => ['files' => $media['files'], 'missing' => $media['missing'], 'bytes' => $media['bytes']],
                'releases' => ($this->releases)(),
                'excluded' => $stats['structure_only'],
                'warnings' => $warnings,
            ];
            BackupManifest::write($this->paths, $manifest);
        } catch (Throwable $e) {
            if ($id !== null) {
                @unlink($this->paths->dump($id));
                @unlink($this->paths->dump($id) . '.part');
            }
            $this->audit('backup.failed', $id ?? '-', ['trigger' => $trigger, 'origin' => $origin, 'error' => mb_substr($e->getMessage(), 0, 500)]);
            $this->releaseSchemaLock($schemaLock);
            flock($lock, LOCK_UN);
            fclose($lock);

            throw $e instanceof BackupError ? $e : new BackupError('io', 'The backup failed: ' . $e->getMessage(), $e);
        }
        $this->releaseSchemaLock($schemaLock);
        $this->audit('backup.run', $id, ['trigger' => $trigger, 'origin' => $origin, 'schema_version' => $stats['schema_version'], 'db_bytes' => $manifest['db']['bytes'], 'media_files' => \count($media['files']), 'media_copied' => $media['copied'], 'missing' => \count($media['missing'])]);
        if ($prune) {
            try {
                $this->prune($origin);
            } catch (Throwable $e) {
                $this->audit('backup.failed', $id, ['trigger' => 'prune', 'origin' => $origin, 'error' => mb_substr($e->getMessage(), 0, 500)]);
            }
        }
        flock($lock, LOCK_UN);
        fclose($lock);

        return ['id' => $id, 'at' => $at, 'trigger' => $trigger, 'schema_version' => $stats['schema_version'], 'db_bytes' => $manifest['db']['bytes'], 'tables' => \count($stats['tables']), 'media_files' => \count($media['files']), 'media_copied' => $media['copied'], 'missing' => $media['missing']];
    }

    /**
     * Every set with a manifest, newest first; a set whose manifest is damaged is listed as broken.
     *
     * @return list<array{id: string, at: int, trigger: string, ok: bool, problem: ?string, manifest: ?Manifest}>
     */
    public function sets(): array
    {
        $out = [];
        foreach (glob($this->paths->sets() . '/B-*.json') ?: [] as $file) {
            $id = basename($file, '.json');
            if (!BackupPaths::validId($id)) {
                continue;
            }
            try {
                $m = BackupManifest::read($this->paths, $id);
                $out[] = ['id' => $id, 'at' => $m['at'], 'trigger' => $m['trigger'], 'ok' => true, 'problem' => null, 'manifest' => $m];
            } catch (BackupError $e) {
                preg_match('/^B-([0-9]{8})-([0-9]{6})/', $id, $d);
                $out[] = ['id' => $id, 'at' => (int) strtotime(($d[1] ?? '19700101') . ' ' . ($d[2] ?? '000000') . ' UTC'), 'trigger' => '?', 'ok' => false, 'problem' => $e->getMessage(), 'manifest' => null];
            }
        }
        usort($out, static fn(array $a, array $b): int => [$b['at'], $b['id']] <=> [$a['at'], $a['id']]);

        return $out;
    }

    /** @return array{id: string, at: int, trigger: string}|null the newest intact scheduled, fallback or manual set */
    public function lastSuccessful(): ?array
    {
        foreach ($this->sets() as $s) {
            if ($s['ok'] && !str_starts_with($s['trigger'], 'pre_')) {
                return ['id' => $s['id'], 'at' => $s['at'], 'trigger' => $s['trigger']];
            }
        }

        return null;
    }

    /**
     * What the dashboard shows (05 §18): the last successful backup, whether one is overdue, and the last failure.
     *
     * @return array{last: ?array{id: string, at: int, trigger: string}, overdue: bool, hours_since: ?int, last_failure: ?string}
     */
    public function status(): array
    {
        $last = $this->lastSuccessful();
        $hours = $last === null ? null : intdiv(max(0, $this->clock->now() - $last['at']), 3600);
        $failure = Sql::row($this->pdo, "SELECT occurred_at, after_text FROM audit_event WHERE action = 'backup.failed' ORDER BY id DESC LIMIT 1");
        $failedAt = $failure === null ? null : (string) $failure['occurred_at'];
        // A failure counts only while it is newer than the last success.
        $stillFailing = $failedAt !== null && ($last === null || strtotime($failedAt . ' UTC') > $last['at']);

        return ['last' => $last, 'overdue' => $last === null || $hours > $this->config->overdueHours, 'hours_since' => $hours, 'last_failure' => $stillFailing ? $failedAt : null];
    }

    /**
     * Proves a set is whole without touching any database: the manifest, the dump's checksum and statement count, and every media file in the store.
     *
     * @return list<string> problems; empty means the set is restorable
     */
    public function verify(string $id): array
    {
        try {
            $m = BackupManifest::read($this->paths, $id);
        } catch (BackupError $e) {
            return [$e->getMessage()];
        }
        $problems = [];
        $gz = $this->paths->dump($id);
        if (!is_file($gz)) {
            return ["The dump of {$id} is missing."];
        }
        if (!hash_equals($m['db']['sha256'], (string) hash_file('sha256', $gz))) {
            return ["The dump of {$id} does not match its checksum (damaged or altered)."];
        }
        try {
            $reader = StatementReader::read($gz);
            $count = 0;
            foreach ($reader as $_) {
                ++$count;
            }
            if ($count !== $m['db']['statements']) {
                $problems[] = "The dump of {$id} holds {$count} statements, the manifest says {$m['db']['statements']}.";
            }
        } catch (BackupError $e) {
            $problems[] = $e->getMessage();
        }
        foreach ($m['media']['files'] as $f) {
            $file = $this->paths->store() . '/' . $f['path'];
            if (!is_file($file)) {
                $problems[] = "Media file {$f['path']} is missing from the backup store.";
            } elseif (!hash_equals($f['sha256'], (string) hash_file('sha256', $file))) {
                $problems[] = "Media file {$f['path']} in the backup store is damaged.";
            }
        }

        return $problems;
    }

    /** A full media archive of a set (weekly or monthly, 05 §18). */
    public function archive(string $id, string $origin = 'cli'): string
    {
        $m = BackupManifest::read($this->paths, $id);
        $this->paths->ensure();
        $zip = $this->paths->archives() . '/media-full-' . $id . '.zip';
        try {
            MediaFiles::archive($m['media']['files'], $this->paths->store(), $zip);
        } catch (Throwable $e) {
            $this->audit('backup.failed', $id, ['trigger' => 'archive', 'origin' => $origin, 'error' => mb_substr($e->getMessage(), 0, 500)]);

            throw $e;
        }
        $this->audit('backup.archive', $id, ['origin' => $origin, 'files' => \count($m['media']['files']), 'bytes' => (int) filesize($zip)]);

        return $zip;
    }

    /**
     * Applies the retention (`Retention`), then removes store files no remaining set names.
     *
     * @return list<string> the ids deleted
     */
    public function prune(string $origin = 'cli'): array
    {
        $sets = array_values(array_filter($this->sets(), static fn(array $s): bool => $s['ok']));
        $delete = Retention::prune(array_map(static fn(array $s): array => ['id' => $s['id'], 'at' => $s['at'], 'trigger' => $s['trigger']], $sets), $this->config);
        foreach ($delete as $id) {
            @unlink($this->paths->manifest($id));
            @unlink($this->paths->manifest($id) . '.sha256');
            @unlink($this->paths->dump($id));
            foreach (glob($this->paths->archives() . '/media-full-' . $id . '.zip') ?: [] as $zip) {
                @unlink($zip);
            }
        }
        $kept = [];
        foreach ($this->sets() as $s) {
            foreach ($s['manifest']['media']['files'] ?? [] as $f) {
                $kept[$f['path']] = true;
            }
        }
        $swept = 0;
        foreach (glob($this->paths->store() . '/[0-9][0-9][0-9][0-9]/*') ?: [] as $file) {
            $rel = substr($file, \strlen($this->paths->store()) + 1);
            if (!isset($kept[$rel]) && preg_match(MediaFiles::PATH_PATTERN, $rel) === 1 && @unlink($file)) {
                ++$swept;
            }
        }
        if ($delete !== [] || $swept > 0) {
            $this->audit('backup.prune', '-', ['origin' => $origin, 'sets' => $delete, 'store_files' => $swept]);
        }

        return $delete;
    }

    private function releaseSchemaLock(bool $held): void
    {
        if ($held) {
            try {
                Sql::run($this->pdo, 'SELECT RELEASE_LOCK(?)', [self::MIGRATION_LOCK]);
            } catch (Throwable) {
                // the lock dies with the connection
            }
        }
    }

    /** @param array<string, mixed> $after */
    private function audit(string $action, string $label, array $after): void
    {
        try {
            (new AuditLog($this->pdo))->record(null, $action, 'backup', null, $label, null, $after);
        } catch (Throwable $e) {
            if (!str_contains($e->getMessage(), '42S02')) { // an unmigrated database has no audit table yet
                error_log('Nova backup: audit failed: ' . $e->getMessage());
            }
        }
    }

    /** Work in progress from an interrupted run: temporary files, and dumps without a manifest. */
    private function sweepTemp(): void
    {
        foreach (glob($this->paths->root . '/db/*.part') ?: [] as $f) {
            @unlink($f);
        }
        Files::removeTree($this->paths->tmp());
        @mkdir($this->paths->tmp(), 0700, true);
        foreach (glob($this->paths->root . '/db/B-*.sql.gz') ?: [] as $dump) {
            $id = basename($dump, '.sql.gz');
            if (BackupPaths::validId($id) && !is_file($this->paths->manifest($id))) {
                @unlink($dump);
            }
        }
    }
}
